// Icons whose name is a single generic token get these when the name alone gives nothing.
let added = 0
for (const icon of icons) {
  const base = new Set(icon.tags)
  const tokens = icon.name.split('-')
  for (const t of tokens) {
    if (t.length > 1 && !base.has(t)) base.add(t)
    for (const s of SYN[t] ?? []) base.add(s)
  }
  // keep the original tags first, then add up to 10 total
  const next = [...icon.tags, ...[...base].filter(t => !icon.tags.includes(t))].slice(0, 10)
  added += next.length - icon.tags.length
  icon.tags = next
}

writeFileSync(path, JSON.stringify(icons, null, 1))
const weak = icons.filter(i => i.tags.length < 3).length
const none = icons.filter(i => i.tags.length === 0).length
console.log(`added ${added} tags; ${weak} icons still under 3 tags, ${none} with none`)
